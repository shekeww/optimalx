// Generates app/content/salla-ids.ts from docs/build/salla-ids.json, the map the
// store writes produced (47 products created on 2026-09-18, see
// docs/build/store-write-log.md). The theme never hard-codes a product id in a
// component; it imports from the generated module, and a re-run after the next
// store write is the only way that module changes.
//
// Run: pnpm gen:salla-ids [--check]
//   --check  exits 1 when the file on disk differs from what would be written
//            (so CI catches a hand edit), and writes nothing.

import fs from 'node:fs';
import path from 'node:path';
import { pathToFileURL } from 'node:url';

const SOURCE = path.join('docs', 'build', 'salla-ids.json');
const TARGET = path.join('app', 'content', 'salla-ids.ts');

/**
 * @typedef {{ sku: string, id: number, path: string, hasImage: boolean, type: string | null }} Entry
 */

/**
 * @param {Record<string, { id: number, url: string, image?: string, type_created?: string }>} source
 * @returns {Entry[]}
 */
export function toEntries(source) {
  return Object.entries(source)
    .map(([sku, value]) => ({
      sku,
      id: value.id,
      // The store's own SEO slug, decoded: it is a route param value, and the
      // router percent-encodes it again when it builds the href. The engine's
      // Link adds the locale segment.
      path: decodeURIComponent(new URL(value.url).pathname),
      hasImage: value.image === 'added',
      type: value.type_created ?? null,
    }))
    .sort((a, b) => a.sku.localeCompare(b.sku));
}

/**
 * @param {Entry[]} entries
 * @returns {string}
 */
export function render(entries) {
  const withImages = entries.filter((entry) => entry.hasImage).length;
  const rows = entries
    .map((entry) => {
      const type = entry.type === null ? 'null' : JSON.stringify(entry.type);
      return `  ${JSON.stringify(entry.sku)}: { id: ${entry.id}, path: ${JSON.stringify(
        entry.path
      )}, hasImage: ${entry.hasImage}, type: ${type} },`;
    })
    .join('\n');
  return `// Generated by scripts/gen-salla-ids.mjs from docs/build/salla-ids.json.
// Do not edit by hand: run \`pnpm gen:salla-ids\` after a store write instead.
//
// ${entries.length} products created on the live store, ${withImages} with a photo
// attached. \`path\` is the store's own SEO slug and already carries the
// \`/p<id>\` suffix the product route matches; the engine \`Link\` adds the locale
// segment. \`type\` is set only where the API created a non-default product type
// (digital, service); \`booking\` items were created as \`service\` and the owner
// converts them in the dashboard (PLAN-final C14).

export interface SallaProductRef {
  /** The catalogue SKU from FINAL-catalogue.md. */
  id: number;
  /** Path on the store, e.g. \`/<slug>/p<id>\`. */
  path: string;
  /** A photo is attached; the rest wait for owner artwork. */
  hasImage: boolean;
  /** \`digital\`, \`service\`, or null for a plain product. */
  type: string | null;
}

export const SALLA_IDS = {
${rows}
} as const satisfies Record<string, SallaProductRef>;

export type SallaSku = keyof typeof SALLA_IDS;

/** The product id for a SKU, or undefined when the SKU is not in the map. */
export function idForSku(sku: string): number | undefined {
  return (SALLA_IDS as Record<string, SallaProductRef>)[sku]?.id;
}

/** The store path for a SKU, or undefined when the SKU is not in the map. */
export function pathForSku(sku: string): string | undefined {
  return (SALLA_IDS as Record<string, SallaProductRef>)[sku]?.path;
}

/** Every id in the map, in SKU order: the "latest products" fallback list. */
export const SALLA_PRODUCT_IDS: number[] = Object.values(
  SALLA_IDS as Record<string, SallaProductRef>
).map((entry) => entry.id);
`;
}

function main(args) {
  const source = JSON.parse(fs.readFileSync(SOURCE, 'utf8'));
  const entries = toEntries(source);
  const output = render(entries);
  if (args.includes('--check')) {
    const current = fs.existsSync(TARGET) ? fs.readFileSync(TARGET, 'utf8') : '';
    if (current !== output) {
      console.error(`${TARGET} is out of date; run pnpm gen:salla-ids`);
      return 1;
    }
    console.log(`gen-salla-ids: ${entries.length} entries, ${TARGET} up to date`);
    return 0;
  }
  fs.mkdirSync(path.dirname(TARGET), { recursive: true });
  fs.writeFileSync(TARGET, output, 'utf8');
  console.log(`gen-salla-ids: wrote ${entries.length} entries to ${TARGET}`);
  return 0;
}

const invokedDirectly =
  process.argv[1] && import.meta.url === pathToFileURL(path.resolve(process.argv[1])).href;
if (invokedDirectly) process.exitCode = main(process.argv.slice(2));
