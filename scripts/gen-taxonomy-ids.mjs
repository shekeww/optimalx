// Generates app/content/taxonomy-ids.ts from docs/build/taxonomy-ids.json, the
// slug-to-id map batch S5's `salla-categories.mjs --apply` writes after it
// creates the 25-node taxonomy on the live store (PLAN-ship Contract A/B,
// shared-file conflicts table: S1 owns this generator, S5 writes the JSON
// input). Mirrors scripts/gen-salla-ids.mjs.
//
// Before S5 has ever run, docs/build/taxonomy-ids.json does not exist yet:
// that is not an error here, it produces an empty map, which is what lets
// `useTaxonomyLinks` fall through to the live category list and then to a
// search fallback (PLAN-final C15) with no id to match by.
//
// Run: node scripts/gen-taxonomy-ids.mjs [--check]
//   --check  exits 1 when the file on disk differs from what would be written
//            (so CI catches a hand edit), and writes nothing.
//
// Not yet wired into package.json (S7 adds the script line at the end of the
// ship program, shared-file conflicts table); run it with `node` directly
// until then.

import fs from 'node:fs';
import path from 'node:path';
import { pathToFileURL } from 'node:url';

const SOURCE = path.join('docs', 'build', 'taxonomy-ids.json');
const TARGET = path.join('app', 'content', 'taxonomy-ids.ts');

/**
 * @param {Record<string, number>} source
 * @returns {string}
 */
export function render(source) {
  const entries = Object.entries(source).sort(([a], [b]) => a.localeCompare(b));
  const rows = entries.map(([slug, id]) => `  ${JSON.stringify(slug)}: ${id},`).join('\n');
  return `// Generated by scripts/gen-taxonomy-ids.mjs from docs/build/taxonomy-ids.json.
// Do not edit by hand: run \`node scripts/gen-taxonomy-ids.mjs\` after a store
// write instead.
//
// ${entries.length} taxonomy slug(s) resolved to a live Salla category id.
// Empty until batch S5 runs \`salla-categories.mjs --apply\`: until then every
// taxonomy link resolves through the live category list or the search
// fallback instead (app/components/listing/useTaxonomyLinks.ts).

export const TAXONOMY_IDS: Record<string, number> = {
${rows}
};
`;
}

function main(args) {
  const source = fs.existsSync(SOURCE) ? JSON.parse(fs.readFileSync(SOURCE, 'utf8')) : {};
  const output = render(source);
  if (args.includes('--check')) {
    const current = fs.existsSync(TARGET) ? fs.readFileSync(TARGET, 'utf8') : '';
    if (current !== output) {
      console.error(`${TARGET} is out of date; run node scripts/gen-taxonomy-ids.mjs`);
      return 1;
    }
    console.log(`gen-taxonomy-ids: ${Object.keys(source).length} entries, ${TARGET} up to date`);
    return 0;
  }
  fs.mkdirSync(path.dirname(TARGET), { recursive: true });
  fs.writeFileSync(TARGET, output, 'utf8');
  console.log(`gen-taxonomy-ids: wrote ${Object.keys(source).length} entries to ${TARGET}`);
  return 0;
}

const invokedDirectly =
  process.argv[1] && import.meta.url === pathToFileURL(path.resolve(process.argv[1])).href;
if (invokedDirectly) process.exitCode = main(process.argv.slice(2));
