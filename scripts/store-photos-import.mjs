#!/usr/bin/env node
// Imports the owner's photographs of the Al Khalidiyah branch (owner brief
// 2026-09-24: the storefront, two shelf shots, the advisory room and the
// waiting area) into `public/assets/store/` as WebP at the widths the branch,
// services and advisory surfaces read, and writes the manifest
// `app/content/store-photos.ts` the components size their `srcset` from.
//
// Sources are NEVER upscaled: the storefront file the owner sent is 415px
// wide, so its largest rendition is 415px and the manifest says so; a surface
// that wants more asks the owner for the original (docs/build/owner-checklist.md).
//
// The wide shelf shot the owner took from the Google Maps listing carries the
// listing's own UI baked into the pixels (a name chip at the physical top-left,
// a map inset at the bottom-left); the crop below removes the left 300px,
// which holds both, and keeps everything else.
//
// Usage: node scripts/store-photos-import.mjs <folder-with-the-six-files>
//   Files expected in that folder (any of these names, first match wins):
//     storefront:    storefront.*   | 57.*
//     shelves:       shelves.*      | 58.*
//     store-wide:    store-wide.*   | store-products.* | 60.*
//     advisory-room: advisory-room.*| 61.*
//     waiting-area:  waiting-area.* | advisory-room-2.* | 62.*
//   (59.* is the Google Maps rating screenshot: data only, never published.)

import fs from 'node:fs';
import path from 'node:path';
import { createRequire } from 'node:module';
import { fileURLToPath } from 'node:url';

const require = createRequire(import.meta.url);
const ROOT = path.resolve(fileURLToPath(new URL('.', import.meta.url)), '..');
const OUT_DIR = path.join(ROOT, 'public', 'assets', 'store');
const MANIFEST = path.join(ROOT, 'app', 'content', 'store-photos.ts');

// sharp is a transitive dependency (pnpm keeps it under .pnpm); resolve it
// from the one package that lists it so this script has no dependency of its own.
function loadSharp() {
  try {
    return require('sharp');
  } catch {
    const pnpmDir = path.join(ROOT, 'node_modules', '.pnpm');
    const hit = fs.readdirSync(pnpmDir).find((name) => name.startsWith('sharp@'));
    if (!hit) throw new Error('store-photos-import: sharp not found under node_modules/.pnpm');
    return require(path.join(pnpmDir, hit, 'node_modules', 'sharp'));
  }
}

const PHOTOS = [
  { slug: 'storefront', names: ['storefront', '57'], crop: null },
  { slug: 'shelves', names: ['shelves', '58'], crop: null },
  { slug: 'store-wide', names: ['store-wide', 'store-products', '60'], crop: { left: 300, top: 0 } },
  { slug: 'advisory-room', names: ['advisory-room', '61'], crop: null },
  { slug: 'waiting-area', names: ['waiting-area', 'advisory-room-2', '62'], crop: null },
];

const WIDTHS = [380, 480, 760, 1160, 1600];
const QUALITY = 82;

function findSource(folder, names) {
  const files = fs.readdirSync(folder);
  for (const name of names) {
    const hit = files.find((file) => path.parse(file).name.toLowerCase() === name);
    if (hit) return path.join(folder, hit);
  }
  return null;
}

async function importOne(sharp, source, photo) {
  let image = sharp(source).rotate();
  const meta = await image.metadata();
  let width = meta.width;
  let height = meta.height;
  if (photo.crop) {
    width -= photo.crop.left;
    height -= photo.crop.top;
    image = image.extract({ left: photo.crop.left, top: photo.crop.top, width, height });
  }
  const base = await image.toBuffer();
  const widths = WIDTHS.filter((w) => w < width);
  widths.push(width);
  const written = [];
  for (const w of widths) {
    const file = w === width ? `${photo.slug}.webp` : `${photo.slug}-${w}.webp`;
    await sharp(base).resize({ width: w, withoutEnlargement: true }).webp({ quality: QUALITY }).toFile(path.join(OUT_DIR, file));
    written.push(w);
  }
  return { slug: photo.slug, width, height, widths: written };
}

function writeManifest(entries) {
  const rows = entries
    .map(
      (e) => `  '${e.slug}': {
    /** The largest rendition; \`<slug>-{w}.webp\` at every other width. */
    photo: '/assets/store/${e.slug}.webp',
    width: ${e.width},
    height: ${e.height},
    widths: [${e.widths.join(', ')}],
  },`
    )
    .join('\n');
  const text = `/**
 * The owner's photographs of the Al Khalidiyah branch (owner brief 2026-09-24),
 * GENERATED by scripts/store-photos-import.mjs. Do not edit by hand; rerun
 * the script with the owner's folder.
 *
 * \`widths\` lists the renditions that exist on disk, smallest first, the last
 * one being the file at \`photo\`. Nothing is upscaled: a surface builds its
 * \`srcset\` from this list, never from a width table of its own, so a small
 * original (the storefront is 415px wide) is served sharp at its own size
 * rather than blurred up to a slot it cannot fill.
 */
export interface StorePhoto {
  /** The largest rendition, under public/. */
  photo: string;
  width: number;
  height: number;
  /** Renditions on disk, ascending; \`photo\` is the last. */
  widths: readonly number[];
}

export type StorePhotoSlug = ${entries.map((e) => `'${e.slug}'`).join(' | ')};

export const STORE_PHOTOS: Record<StorePhotoSlug, StorePhoto> = {
${rows}
};

const WEBP = '.webp';

/** \`<slug>.webp\` at the largest width, \`<slug>-{w}.webp\` at every other. */
export function storePhotoSrc(entry: StorePhoto, width: number): string {
  if (width === entry.width) return entry.photo;
  return \`\${entry.photo.slice(0, -WEBP.length)}-\${width}\${WEBP}\`;
}

/** The full \`srcset\` value for one photo's own renditions. */
export function storePhotoSrcSet(entry: StorePhoto): string {
  return entry.widths.map((w) => \`\${storePhotoSrc(entry, w)} \${w}w\`).join(', ');
}
`;
  fs.writeFileSync(MANIFEST, text);
}

async function main() {
  const folder = process.argv[2];
  if (!folder || !fs.existsSync(folder)) {
    console.error('usage: node scripts/store-photos-import.mjs <folder-with-the-owner-files>');
    process.exit(1);
  }
  const sharp = loadSharp();
  fs.mkdirSync(OUT_DIR, { recursive: true });
  const entries = [];
  for (const photo of PHOTOS) {
    const source = findSource(folder, photo.names);
    if (!source) {
      console.log(`skip ${photo.slug}: no source file (looked for ${photo.names.join(', ')})`);
      continue;
    }
    const entry = await importOne(sharp, source, photo);
    entries.push(entry);
    console.log(`${entry.slug}: ${entry.width}x${entry.height}, widths ${entry.widths.join('/')}`);
  }
  if (entries.length === 0) {
    console.error('store-photos-import: nothing imported');
    process.exit(1);
  }
  writeManifest(entries);
  console.log(`wrote ${path.relative(ROOT, MANIFEST)} (${entries.length} photos)`);
}

main().catch((error) => {
  console.error(error);
  process.exit(1);
});
